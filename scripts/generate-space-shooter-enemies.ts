type EnemyDef = {
  name: string;
  frames: ReturnType<typeof frameFromRows>[];
};

const enemies: EnemyDef[] = [
  { name: "scout", frames: [scoutA, scoutB] },
  { name: "cruiser", frames: [cruiserA, cruiserB] },
  { name: "drifter", frames: [drifterA, drifterB, drifterC] },
];

function writeSheet(name: string, frames: typeof scoutA[]): void {
  const stitched = stitchFramesHorizontal(frames);
  const rgba = indicesToRgba(stitched.width, stitched.height, stitched.cells, BEAST2D_16);
  const path = join(OUT_DIR, `${name}-sheet.32x32.png`);
  writeRgbaPng(path, stitched.width, stitched.height, rgba);
  console.log(`Wrote ${path} (${frames.length} frames)`);
}

for (const enemy of enemies) {
  for (let i = 0; i < enemy.frames.length; i += 1) {
    const f = enemy.frames[i]!;
    const rgba = indicesToRgba(f.width, f.height, f.cells, BEAST2D_16);
    writeRgbaPng(
      join(OUT_DIR, `${enemy.name}-f${i}.32x32.png`),
      f.width,
      f.height,
      rgba,
    );
  }
  writeSheet(enemy.name, enemy.frames);
}

const bulletRgba = indicesToRgba(bullet.width, bullet.height, bullet.cells, BEAST2D_16);
writeRgbaPng(join(process.cwd(), "public/space-shooter/bullet.16x16.png"), bullet.width, bullet.height, bulletRgba);
console.log("Wrote bullet.16x16.png");

/** Vertical contact sheet: all single frames for review. */
const allFrames = enemies.flatMap((e) => e.frames);
const contactW = FRAME * 4;
const contactH = FRAME * Math.ceil(allFrames.length / 4);
const contactCells = new Int8Array(contactW * contactH).fill(-1);
for (let i = 0; i < allFrames.length; i += 1) {
  const col = i % 4;
  const row = Math.floor(i / 4);
  const f = allFrames[i]!;
  for (let y = 0; y < FRAME; y += 1) {
    for (let x = 0; x < FRAME; x += 1) {
      contactCells[(row * FRAME + y) * contactW + col * FRAME + x] =
        f.cells[y * FRAME + x]!;
    }
  }
}
const contactRgba = indicesToRgba(contactW, contactH, contactCells, BEAST2D_16);
writeRgbaPng(join(OUT_DIR, "contact-sheet.png"), contactW, contactH, contactRgba);
console.log(`Wrote contact-sheet.png (${allFrames.length} frames)`);
